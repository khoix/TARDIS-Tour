import type { AnchorLevel, DoorAnchor, EvidenceRecord, RoomNode } from './types';

/**
 * Room/node register from research bible §17.1 (topology and evidence only; no positions).
 * `placed: true` rooms form the v1 stable snapshot; everything else is inventory-only and
 * must never be rendered as a floating volume (research §F3.5).
 */

function anchor(
  id: string,
  label: string,
  level: AnchorLevel,
  observed: boolean,
  note?: string,
): DoorAnchor {
  return note === undefined
    ? { id, label, level, observed, canonAzimuthDeg: null }
    : { id, label, level, observed, canonAzimuthDeg: null, note };
}

function ev(grade: EvidenceRecord['grade'], sourceIds: string[], note: string): EvidenceRecord {
  return { grade, sourceIds, note };
}

